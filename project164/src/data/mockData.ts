const stagesBase = [
  { stageName: "选校" as const },
  { stageName: "文书准备" as const },
  { stageName: "材料提交" as const },
  { stageName: "等待录取" as const },
  { stageName: "录取结果" as const },
  { stageName: "签证" as const },
  { stageName: "入学" as const },
];

const createStages = (
  startOffset: number,
  completedStages: number,
  currentProgress: number
) => {
  return stagesBase.map((s, idx) => ({
    id: generateId(),
    stageName: s.stageName,
    progress:
      idx < completedStages
        ? 100
        : idx === completedStages
          ? currentProgress
          : 0,
    startDate: addDays(now, startOffset + idx * 14),
    dueDate: addDays(now, startOffset + idx * 14 + 12),
    isCompleted: idx < completedStages,
  }));
};

