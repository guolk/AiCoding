const generateGpsTrack = (startLat: number, startLng: number, endLat: number, endLng: number, points: number, voyageId: string) => {
  const track = [];
  for (let i = 0; i <= points; i++) {
    const ratio = i / points;
    const lat = startLat + (endLat - startLat) * ratio + (Math.random() - 0.5) * 0.02;
    const lng = startLng + (endLng - startLng) * ratio + (Math.random() - 0.5) * 0.02;
    track.push({
      id: `gps-${voyageId}-${i}`,
      voyageId,
      latitude: lat,
      longitude: lng,
      speed: 4 + Math.random() * 4,
      timestamp: new Date(2024, 5, 1, 8, i * 15).toISOString(),
    });
  }
  return track;
};

