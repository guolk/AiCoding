export function getCityById(id: string): City | undefined {
  return CITIES.find(c => c.id === id);
}

export function getTopCities(limit: number = 10): City[] {
  return [...CITIES].sort((a, b) => b.overallScore - a.overallScore).slice(0, limit);
}

export function getCitiesByTag(tag: string): City[] {
  return CITIES.filter(c => c.tags.includes(tag));
}

export function getBudgetCities(): City[] {
  return getCitiesByTag('budget').sort((a, b) => a.monthlyCostUsd - b.monthlyCostUsd);
}

export function getInternetCities(): City[] {
  return [...CITIES].sort((a, b) => b.avgInternetMbps - a.avgInternetMbps);
}

export function getCommunityCities(): City[] {
  return [...CITIES].sort((a, b) => b.coworkingSpaces - a.coworkingSpaces);
}
