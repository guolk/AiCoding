const generateCoordinates = (centerLat: number, centerLng: number, count: number): [number, number][] => {
  const coords: [number, number][] = [];
  for (let i = 0; i < count; i++) {
    coords.push([
      centerLat + (Math.random() - 0.5) * 0.1,
      centerLng + (Math.random() - 0.5) * 0.1,
    ]);
  }
  return coords;
};

